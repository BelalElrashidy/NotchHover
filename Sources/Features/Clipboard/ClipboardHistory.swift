import AppKit

struct ClipboardItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable {
        case text
        case link
        case file
        case image
    }

    let id: UUID
    let kind: Kind
    var text: String?
    var filePaths: [String]?
    /// Image files live beside the history, named by item id.
    var imageFileName: String?
    var imageWidth: Double?
    var imageHeight: Double?
    var sourceBundleIdentifier: String?
    var sourceName: String?
    var copied: Date
    var isPinned: Bool
    var copyCount: Int

    var preview: String {
        switch kind {
        case .text, .link:
            return (text ?? "").replacingOccurrences(of: "\n", with: " ").trimmingCharacters(in: .whitespaces)
        case .file:
            let names = (filePaths ?? []).map { URL(fileURLWithPath: $0).lastPathComponent }
            return names.count > 1 ? "\(names[0]) and \(names.count - 1) more" : (names.first ?? "File")
        case .image:
            if let w = imageWidth, let h = imageHeight { return "Image · \(Int(w))×\(Int(h))" }
            return "Image"
        }
    }

    var symbol: String {
        switch kind {
        case .text: return "text.alignleft"
        case .link: return "link"
        case .file: return "doc"
        case .image: return "photo"
        }
    }
}

/// Clipboard history, kept on this Mac only.
///
/// macOS has no clipboard-changed notification, so this checks the pasteboard's change
/// counter twice a second — cheap, and the same approach every clipboard manager uses.
final class ClipboardHistory {
    static let shared = ClipboardHistory()

    enum Key {
        static let paused = "ClipboardPaused"
        static let excludedApps = "ClipboardExcludedApps"
    }

    /// The nspasteboard.org convention: password managers and other apps mark copies
    /// that must never be stored. Anything carrying these is skipped outright.
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type"
    ]

    /// Never recorded, even if an app forgets to mark its copies.
    static let defaultExcludedApps = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
        "com.dashlane.dashlanephonefinal"
    ]

    private static let directoryName = "Clipboard"
    private static let indexName = "Clipboard/history.json"
    private static let maximumItems = 250
    private static let maximumImagePixels: CGFloat = 1600

    private(set) var items: [ClipboardItem] = []
    private var observers: [UUID: () -> Void] = [:]
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var ignoreCount = 0

    /// Previews fill the history without touching the real one.
    var persists = true

    private init() {
        items = LocalStore.load([ClipboardItem].self, from: Self.indexName) ?? []
    }

    var isPaused: Bool {
        get { UserDefaults.standard.bool(forKey: Key.paused) }
        set {
            UserDefaults.standard.set(newValue, forKey: Key.paused)
            notify()
        }
    }

    private var excludedApps: Set<String> {
        Set(Self.defaultExcludedApps + (UserDefaults.standard.stringArray(forKey: Key.excludedApps) ?? []))
    }

    func start() {
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    @discardableResult
    func addObserver(_ handler: @escaping () -> Void) -> UUID {
        let id = UUID()
        observers[id] = handler
        return id
    }

    func removeObserver(_ id: UUID) {
        observers[id] = nil
    }

    /// When the app itself writes to the clipboard, that is not a new entry.
    func ignoreNextChange() {
        ignoreCount += 1
    }

    // MARK: - Recording

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        if ignoreCount > 0 {
            ignoreCount -= 1
            return
        }
        guard isPaused == false else { return }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.privateTypes) else {
            Log.system.notice("Clipboard: skipped a copy marked private")
            return
        }

        let source = NSWorkspace.shared.frontmostApplication
        if let bundle = source?.bundleIdentifier, excludedApps.contains(bundle) {
            Log.system.notice("Clipboard: skipped a copy from an excluded app")
            return
        }

        guard var item = read(pasteboard) else { return }
        item.sourceBundleIdentifier = source?.bundleIdentifier
        item.sourceName = source?.localizedName
        record(item)
    }

    private func read(_ pasteboard: NSPasteboard) -> ClipboardItem? {
        func make(_ kind: ClipboardItem.Kind) -> ClipboardItem {
            ClipboardItem(id: UUID(), kind: kind, copied: Date(), isPinned: false, copyCount: 1)
        }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           urls.isEmpty == false {
            var item = make(.file)
            item.filePaths = urls.map(\.path)
            return item
        }

        if let string = pasteboard.string(forType: .string),
           string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty == false {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            let isLink = trimmed.contains(" ") == false && trimmed.contains("\n") == false
                && (trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://"))
            var item = make(isLink ? .link : .text)
            item.text = string
            return item
        }

        if let image = NSImage(pasteboard: pasteboard), let file = saveImage(image) {
            var item = make(.image)
            item.imageFileName = file.name
            item.imageWidth = file.size.width
            item.imageHeight = file.size.height
            return item
        }

        return nil
    }

    private func record(_ item: ClipboardItem) {
        // Copying the same thing again moves it to the top rather than duplicating it.
        if let index = items.firstIndex(where: { matches($0, item) }) {
            var existing = items.remove(at: index)
            existing.copied = Date()
            existing.copyCount += 1
            existing.sourceBundleIdentifier = item.sourceBundleIdentifier ?? existing.sourceBundleIdentifier
            existing.sourceName = item.sourceName ?? existing.sourceName
            if let orphan = item.imageFileName { deleteImage(orphan) }
            items.insert(existing, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        trim()
        Log.system.notice("Clipboard: recorded \(item.kind.rawValue, privacy: .public)")
        changed()
    }

    private func matches(_ a: ClipboardItem, _ b: ClipboardItem) -> Bool {
        guard a.kind == b.kind else { return false }
        switch a.kind {
        case .text, .link: return a.text == b.text
        case .file: return a.filePaths == b.filePaths
        case .image: return a.imageWidth == b.imageWidth && a.imageHeight == b.imageHeight
            && imageData(a) == imageData(b)
        }
    }

    private func trim() {
        while items.filter({ $0.isPinned == false }).count > Self.maximumItems,
              let index = items.lastIndex(where: { $0.isPinned == false }) {
            let removed = items.remove(at: index)
            if let file = removed.imageFileName { deleteImage(file) }
        }
    }

    // MARK: - Actions

    /// Puts an item back on the clipboard.
    func copy(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        switch item.kind {
        case .text, .link:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .file:
            pasteboard.writeObjects((item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            if let image = image(for: item) {
                pasteboard.writeObjects([image])
            }
        }

        ignoreNextChange()

        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.copied = Date()
            items.insert(moved, at: 0)
            changed()
        }
    }

    /// Copies, then types ⌘V into whatever app is in front. Needs Accessibility; without
    /// it this is just a copy.
    func paste(_ item: ClipboardItem) {
        copy(item)
        guard AXIsProcessTrusted() else { return }

        let source = CGEventSource(stateID: .combinedSessionState)
        let vKey: CGKeyCode = 0x09
        let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    func togglePin(_ id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].isPinned.toggle()
        changed()
    }

    func delete(_ id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        let removed = items.remove(at: index)
        if let file = removed.imageFileName { deleteImage(file) }
        changed()
    }

    /// Pinned items survive a clear.
    func clear() {
        for item in items where item.isPinned == false {
            if let file = item.imageFileName { deleteImage(file) }
        }
        items.removeAll { $0.isPinned == false }
        changed()
    }

    func search(_ query: String) -> [ClipboardItem] {
        let sorted = items.sorted {
            if $0.isPinned != $1.isPinned { return $0.isPinned }
            return $0.copied > $1.copied
        }
        let trimmed = query.trimmingCharacters(in: .whitespaces)
        guard trimmed.isEmpty == false else { return sorted }
        return sorted.filter {
            $0.preview.localizedCaseInsensitiveContains(trimmed)
                || ($0.sourceName ?? "").localizedCaseInsensitiveContains(trimmed)
        }
    }

    /// Used by previews to show the widget with sample content.
    func loadSample(_ sample: [ClipboardItem]) {
        persists = false
        items = sample
        notify()
    }

    // MARK: - Images

    private var imageDirectory: URL {
        LocalStore.url(Self.directoryName)
    }

    func image(for item: ClipboardItem) -> NSImage? {
        guard let name = item.imageFileName else { return nil }
        return NSImage(contentsOf: imageDirectory.appendingPathComponent(name))
    }

    private func imageData(_ item: ClipboardItem) -> Data? {
        guard let name = item.imageFileName else { return nil }
        return try? Data(contentsOf: imageDirectory.appendingPathComponent(name))
    }

    /// Stored downscaled, so a copied 6K screenshot does not become a 40MB file.
    private func saveImage(_ image: NSImage) -> (name: String, size: CGSize)? {
        guard persists, let rep = image.representations.first else { return nil }
        let original = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
        guard original.width > 0, original.height > 0 else { return nil }

        let scale = min(1, Self.maximumImagePixels / max(original.width, original.height))
        let target = NSSize(width: (original.width * scale).rounded(), height: (original.height * scale).rounded())
        guard let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: Int(target.width), pixelsHigh: Int(target.height),
                                            bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                            colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0) else { return nil }
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: bitmap)
        image.draw(in: NSRect(origin: .zero, size: target))
        NSGraphicsContext.restoreGraphicsState()

        guard let png = bitmap.representation(using: .png, properties: [:]) else { return nil }
        LocalStore.ensureDirectory(imageDirectory)
        let name = UUID().uuidString + ".png"
        let url = imageDirectory.appendingPathComponent(name)
        do {
            try png.write(to: url, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            return (name, original)
        } catch {
            return nil
        }
    }

    private func deleteImage(_ name: String) {
        try? FileManager.default.removeItem(at: imageDirectory.appendingPathComponent(name))
    }

    // MARK: - Saving

    private func notify() {
        observers.values.forEach { $0() }
    }

    private func changed() {
        notify()
        guard persists else { return }
        LocalStore.ensureDirectory(imageDirectory)
        LocalStore.save(items, to: Self.indexName)
    }
}
